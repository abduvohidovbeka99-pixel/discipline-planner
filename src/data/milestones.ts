/** Motivational phrase under the overall progress ring. */
export function progressMessage(p: number): string {
  if (p >= 100) return 'Цель достигнута — ты сделал это! 🏆';
  if (p >= 75) return 'Финишная прямая — осталось совсем немного';
  if (p >= 50) return 'Больше половины пути пройдено';
  if (p >= 25) return 'Ритм найден — не сбавляй';
  return 'Начало положено — каждая галочка приближает к цели';
}
